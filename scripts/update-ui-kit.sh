#!/usr/bin/env bash
# Refresh the ui-kit:
#   1. Re-copy the skills listed below from the latest default branch of each fork into .claude/skills/
#   2. Pull the latest of the awesome-design-md submodule in ui-kit/
# Skills are copied, not linked, so they load in any clone (including cloud sessions without submodules).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

# <fork repo> <path inside fork> <skill name in .claude/skills>
SKILLS=(
  "lea-tinoso/taste-skill skills/taste-skill design-taste-frontend"
  "lea-tinoso/agent-skills skills/react-best-practices vercel-react-best-practices"
  "lea-tinoso/agent-skills skills/composition-patterns vercel-composition-patterns"
  "lea-tinoso/agent-skills skills/react-view-transitions vercel-react-view-transitions"
  "lea-tinoso/agent-skills skills/web-design-guidelines web-design-guidelines"
)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
lock=.claude/skills/skills.lock
echo "# Generated by scripts/update-ui-kit.sh. Do not edit the copied skills; change the fork instead." > "$lock"

for entry in "${SKILLS[@]}"; do
  read -r repo path name <<< "$entry"
  src="$tmp/${repo#*/}"
  if [ ! -d "$src" ]; then
    git clone --quiet --depth 1 "https://github.com/$repo.git" "$src"
  fi
  rm -rf ".claude/skills/$name"
  cp -R "$src/$path" ".claude/skills/$name"
  echo "$name $repo@$(git -C "$src" rev-parse --short HEAD) $path" >> "$lock"
done

git submodule sync --quiet
git submodule update --init --remote --merge --quiet

if git diff --quiet HEAD -- .claude/skills ui-kit && [ -z "$(git status --porcelain -- .claude/skills ui-kit)" ]; then
  echo "ui-kit is already up to date."
else
  echo "Changed:"
  git status --short -- .claude/skills ui-kit | sed 's/^/  /' | head -30
  echo
  echo "Commit with: git add -A .claude/skills ui-kit && git commit -m 'Update ui-kit'"
fi
